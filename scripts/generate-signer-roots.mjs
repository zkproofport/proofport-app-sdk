#!/usr/bin/env node
/**
 * Writes packages/core/src/signerRoots.generated.ts: the signer-list Merkle
 * root each attestation circuit's proof must carry, computed from the signer
 * lists the provers actually build their trees from.
 *
 * Why: coinbase_attestation, coinbase_country_attestation and giwa_attestation
 * take `signer_list_merkle_root` as a PUBLIC INPUT. The circuit proves the
 * attestation was signed by a member of the tree with that root -- whatever
 * tree the prover chose. A proof over a tree of the prover's own keys verifies
 * unless the verifier compares the root with the published signer set.
 *
 * Sources (read with `git show origin/main:<path>` in each checkout, so the
 * checkouts may sit on any branch; fetch first):
 *   proofport-app  src/config/contracts.ts   AUTHORIZED_SIGNERS        (mobile prover, Coinbase)
 *   proofport-app  src/utils/giwaKyc.ts      GIWA_AUTHORIZED_SIGNERS   (mobile prover, GIWA)
 *   proofport-ai   src/config/contracts.ts   AUTHORIZED_SIGNERS, GIWA_AUTHORIZED_SIGNERS (server prover)
 *   openstoa       src/lib/proof-issuer.ts   COINBASE_SIGNERS          (cross-check only)
 * The lists must agree, IN ORDER (the order fixes the tree), or this stops.
 *
 * Tree, as both provers build it (proofport-ai src/input/merkleTree.ts, and
 * the circuits' coinbase-libs/src/merkle.nr that checks it): leaf =
 * keccak256(20 address bytes); node = keccak256(left || right); an odd layer
 * duplicates its last node.
 *
 *   node scripts/generate-signer-roots.mjs           # write
 *   node scripts/generate-signer-roots.mjs --check   # exit 1 on drift
 *
 * Prerequisites: node >= 18, git, ethers installed (npm ci), and the
 * proofport-app, proofport-ai and openstoa checkouts in the superproject.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ethers } from 'ethers';

const check = process.argv.includes('--check');
const git = (cwd, ...a) => execFileSync('git', ['-C', cwd, ...a], { encoding: 'utf8' });

const sdkRoot = git(process.cwd(), 'rev-parse', '--show-toplevel').trim();
const superproject = git(process.cwd(), 'rev-parse', '--show-superproject-working-tree').trim();
const repo = superproject || sdkRoot;
const REF = 'origin/main';

function readList(checkout, path, name) {
  const dir = join(repo, checkout);
  if (!existsSync(dir)) throw new Error(`No ${checkout} checkout at ${dir}.`);
  const sha = git(dir, 'rev-parse', '--verify', `${REF}^{commit}`).trim();
  const source = git(dir, 'show', `${sha}:${path}`);
  const m = source.match(new RegExp(`\\b${name}\\s*=\\s*\\[([^\\]]*)\\]`));
  if (!m) throw new Error(`${checkout}/${path}: no ${name} = [...] at ${sha}`);
  const list = [...m[1].matchAll(/'(0x[0-9a-fA-F]{40})'/g)].map(x => ethers.getAddress(x[1]));
  if (list.length === 0) throw new Error(`${checkout}/${path}: ${name} is empty at ${sha}`);
  return { list, where: `${checkout}@${sha.slice(0, 7)}:${path}#${name}` };
}

function agree(label, sources) {
  const [first, ...rest] = sources;
  for (const s of rest) {
    if (JSON.stringify(s.list) !== JSON.stringify(first.list)) {
      throw new Error(`${label}: ${s.where} lists ${s.list.join(', ')} but ${first.where} lists ${first.list.join(', ')}`);
    }
  }
  return first.list;
}

function merkleRoot(addresses) {
  let layer = addresses.map(a => ethers.keccak256(ethers.getBytes(a)));
  while (layer.length > 1) {
    const next = [];
    for (let i = 0; i < layer.length; i += 2) {
      next.push(ethers.keccak256(ethers.concat([layer[i], layer[i + 1] ?? layer[i]])));
    }
    layer = next;
  }
  return layer[0].toLowerCase();
}

const coinbaseSources = [
  readList('proofport-app', 'src/config/contracts.ts', 'AUTHORIZED_SIGNERS'),
  readList('proofport-ai', 'src/config/contracts.ts', 'AUTHORIZED_SIGNERS'),
  readList('openstoa', 'src/lib/proof-issuer.ts', 'COINBASE_SIGNERS'),
];
const giwaSources = [
  readList('proofport-app', 'src/utils/giwaKyc.ts', 'GIWA_AUTHORIZED_SIGNERS'),
  readList('proofport-ai', 'src/config/contracts.ts', 'GIWA_AUTHORIZED_SIGNERS'),
];
const coinbase = agree('Coinbase signers', coinbaseSources);
const giwa = agree('GIWA signers', giwaSources);

const sets = {
  COINBASE: { signers: coinbase, root: merkleRoot(coinbase), sources: coinbaseSources.map(s => s.where) },
  GIWA: { signers: giwa, root: merkleRoot(giwa), sources: giwaSources.map(s => s.where) },
};

const lines = [
  '// GENERATED by scripts/generate-signer-roots.mjs -- do not edit by hand.',
  '// Roots are computed from the signer lists below; the lists are read from',
  '// the provers that build the trees, which must agree in order.',
  '',
  'export interface SignerSet {',
  '  /** Signer addresses, checksummed, in tree order. */',
  '  readonly signers: readonly string[];',
  '  /** keccak Merkle root of `signers` (leaf keccak256(address), odd layer duplicates its last node). */',
  '  readonly root: string;',
  '  /** Where the list was read and cross-checked. */',
  '  readonly sources: readonly string[];',
  '}',
  '',
];
for (const [name, set] of Object.entries(sets)) {
  lines.push(`export const ${name}_SIGNER_SET: SignerSet = Object.freeze({`);
  lines.push(`  signers: Object.freeze([${set.signers.map(s => `'${s}'`).join(', ')}]),`);
  lines.push(`  root: '${set.root}',`);
  lines.push(`  sources: Object.freeze([${set.sources.map(s => `'${s}'`).join(', ')}]),`);
  lines.push('});', '');
}
const output = lines.join('\n');
const target = join(sdkRoot, 'packages/core/src/signerRoots.generated.ts');
if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error(`${target} is out of date with the provers' signer lists. Run without --check.`);
    process.exit(1);
  }
  console.log(`${target} matches the provers' signer lists.`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${target}: Coinbase ${sets.COINBASE.root}, GIWA ${sets.GIWA.root}.`);
}
